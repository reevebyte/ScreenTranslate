use screentrans_core::{
    config::*,
    error::{AppError, ErrorCode},
    types::*,
};
use std::path::PathBuf;
use ts_rs::TS;

fn main() -> std::result::Result<(), Box<dyn std::error::Error>> {
    let mut text = String::from("// Generated by `pnpm types`. Do not edit by hand.\n\n");
    let typescript = ts_rs::Config::default();
    macro_rules! emit { ($($ty:ty),* $(,)?) => { $(text.push_str(&format!("export {}\n\n", <$ty>::decl(&typescript)));)* }; }
    emit!(
        ErrorCode,
        AppError,
        Rect,
        MonitorInfo,
        FrameMetadata,
        TextBlock,
        JobStage,
        JobStatus,
        TranslationSession,
        PlatformCapabilities,
        TranslationItem,
        TranslatedItem,
        ProviderId,
        ProviderConfig,
        Theme,
        OcrEngine,
        OcrProtocol,
        CustomOcrConfig,
        OcrConfig,
        Hotkeys,
        Appearance,
        Config,
        Bootstrap,
        MigrationReport
    );
    let path =
        PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../apps/desktop/src/lib/generated.ts");
    if std::env::args().any(|v| v == "--check") {
        if std::fs::read_to_string(&path)? != text {
            return Err("Generated TypeScript types are out of date; run pnpm types".into());
        }
    } else {
        std::fs::create_dir_all(path.parent().unwrap())?;
        std::fs::write(path, text)?;
        let defaults = PathBuf::from(env!("CARGO_MANIFEST_DIR"))
            .join("../../apps/desktop/src/lib/default-config.json");
        std::fs::write(defaults, serde_json::to_string_pretty(&Config::default())?)?;
    }
    Ok(())
}
